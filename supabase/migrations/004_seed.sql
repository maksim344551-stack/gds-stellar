-- =============================================================================
-- 004_seed.sql
-- GDS «Джедес»: начальное содержимое справочника (контент, не тестовые данные).
-- =============================================================================
-- Что вносит файл: 1 бренд, 1 категорию, 10 вкусов линейки Stellar, 1 точку
-- продаж. Паролей, ключей и данных пользователей здесь нет.
--
-- Источник текстов: ТЗ владельца от 2026-10-08. Описания вкусов нейтральные
-- (характеристики ароматического профиля), без оценок и призывов. Ничего сверх
-- ТЗ не добавлено.
--
-- Известные расхождения с сайтом (подробности: docs/adr/0001-supabase-backend.md):
--   * десятый вкус в ТЗ называется Isida (описание общее, уточнить у заказчика),
--     а в коде сайта (src/data.js) он называется Auris, папайя. Здесь по ТЗ;
--   * у Capella в ТЗ написано «мускусный виноград», на сайте «мускатный».
--     Здесь по ТЗ; если это опечатка, исправление: один UPDATE из ADR.
--
-- Телефон, e-mail, адрес и координаты точки взяты из ТЗ без изменений.
-- Координаты НЕ проверялись.
--
-- Повторный запуск безопасен: уже существующие строки не дублируются и не
-- перезаписываются (правки, сделанные позже в админке или Table Editor,
-- сохраняются). Строки ищутся по ключам: бренд по имени, категория и вкус по
-- slug, точка по названию и адресу. Если вы переименовали ключ (например,
-- slug isida в auris), повторный запуск вернёт строку под старым ключом: тогда
-- сначала поправьте тексты в этом файле. Выполнять четвёртым, после 001-003
-- (самому файлу нужны только таблицы из 001_init.sql).
-- =============================================================================

begin;

-- 1. Бренд ------------------------------------------------------------------
insert into public.brands (name, full_name, country, description)
select
  'GDS Джедес',
  'Generation & Delivery Smoke',
  'Россия',
  'Кальянный табак. Купаж из четырёх сортов: оберточный сигарный лист, Берли, Вирджиния Ред в обработке Кавендиш, Вирджиния Голд естественной ферментации. Фасовка: банка 25 г, термос-полусфера с отсекателем, обечайка.'
where not exists (
  select 1 from public.brands where name = 'GDS Джедес'
);

-- 2. Категория --------------------------------------------------------------
insert into public.categories (name, slug)
values ('Кальянный табак', 'hookah-tobacco')
on conflict (slug) do nothing;

-- 3. Вкусы линейки Stellar --------------------------------------------------
-- У всех: вес 25 г, линейка Stellar, крепость не указана (nicotine_mg = null),
-- вкус активен, updated_at пусто (строку ещё не меняли).
-- Подпись (tagline) пуста намеренно: в списке вкусов ТЗ её нет, а 'Discover Star'
-- в ТЗ приведено лишь как пример значения колонки, и рекламный ли это слоган,
-- решает юрист. Если владелец решит иначе, одна правка: update public.products
-- set tagline = 'Discover Star' where line = 'Stellar' (см. docs/adr).
-- Колонки порядка вкусов в ТЗ нет. Чтобы порядок из ТЗ (Altair, Betelgeuse, Vega,
-- ...) сохранялся при сортировке по created_at, у вкусов created_at различается
-- на одну миллисекунду по номеру n.
insert into public.products
  (brand_id, category_id, name, slug, line, tagline, description, aroma_profile, weight_g, is_active, created_at)
select
  b.id,
  c.id,
  v.name,
  v.slug,
  'Stellar',
  null,
  v.description,
  v.aroma_profile,
  25,
  true,
  now() + v.n * interval '1 millisecond'
from (
  values
    (1,  'Altair',     'altair',     'мята',
     'Холодная сладкая мята с оттенком американских мятных леденцов.'),
    (2,  'Betelgeuse', 'betelgeuse', 'роза, виноград',
     'Цветочный аромат розы с фруктовыми оттенками винограда и лёгкой кислинкой.'),
    (3,  'Vega',       'vega',       'лесные ягоды',
     'Ягодный профиль с нотами черники, сандала и железного дерева.'),
    (4,  'Naos',       'naos',       'орчата',
     'Молочный аромат мексиканского напитка с корицей и миндалём.'),
    (5,  'Proxima',    'proxima',    'лимон, лайм',
     'Сладкий лимонный леденец с нотами лаймовой цедры.'),
    (6,  'Sirius',     'sirius',     'чистый купаж',
     'Без ароматических добавок. Ноты шоколада от обработки Кавендиш, лёгкие фруктовые ноты Вирджинии, крепость оберточного листа.'),
    (7,  'Alcor',      'alcor',      'нектарин, ананас',
     'Сочетание нектарина и ананаса.'),
    (8,  'Capella',    'capella',    'мускусный виноград',
     'Цветочный профиль с белым мускусным виноградом.'),
    (9,  'Mira',       'mira',       'вишня, ванильная кола',
     'Аромат газированного вишнёвого напитка с оттенками ванильной колы.'),
    (10, 'Isida',      'isida',      'сладкий душистый',
     'Сладкий душистый профиль.')
) as v (n, name, slug, aroma_profile, description)
cross join (
  select id from public.brands where name = 'GDS Джедес' order by created_at, id limit 1
) as b
cross join (
  select id from public.categories where slug = 'hookah-tobacco'
) as c
on conflict (slug) do nothing;

-- 4. Точка продаж -----------------------------------------------------------
insert into public.stores
  (name, address, city, latitude, longitude, phone, email)
select
  'GDS, Колпино, Финляндская 35',
  'Россия, Санкт-Петербург, Колпино, Финляндская ул., 35',
  'Санкт-Петербург',
  59.7479,
  30.5884,
  '8 800 300-49-99',
  'mtechno.tobacco@gmail.com'
where not exists (
  select 1
  from public.stores
  where name = 'GDS, Колпино, Финляндская 35'
    and address = 'Россия, Санкт-Петербург, Колпино, Финляндская ул., 35'
);

-- 5. Самопроверка: все десять вкусов на месте -------------------------------
-- Если бренд или категория не нашлись, вставка вкусов выше молча ничего не
-- добавила бы. Эта проверка превращает такую ситуацию в ошибку и откат.
do $$
begin
  if (select count(*)
      from public.products
      where slug in ('altair', 'betelgeuse', 'vega', 'naos', 'proxima',
                     'sirius', 'alcor', 'capella', 'mira', 'isida')) <> 10 then
    raise exception 'GDS 004: в products нет всех десяти вкусов Stellar; ничего не применено';
  end if;
end;
$$;

commit;
